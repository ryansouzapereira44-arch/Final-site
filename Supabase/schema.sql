-- 8. Função SQL no servidor para ranking "CLIENTES MAIS FIÉIS"
-- Considera apenas pedidos confirmados (status NOT IN ('Pendente', 'Cancelado'))
-- e soma somente subtotal de produtos (frete NÃO entra na soma).
CREATE OR REPLACE FUNCTION public.get_loyal_customers_ranking(
  p_start_at TIMESTAMPTZ DEFAULT NULL,
  p_end_at TIMESTAMPTZ DEFAULT NULL,
  p_search TEXT DEFAULT '',
  p_neighborhood TEXT DEFAULT '',
  p_inactive_only BOOLEAN DEFAULT FALSE,
  p_sort_by TEXT DEFAULT 'total_spent'
)
RETURNS TABLE (
  user_id BIGINT,
  customer_name TEXT,
  customer_email TEXT,
  customer_whatsapp TEXT,
  main_neighborhood TEXT,
  orders_count BIGINT,
  total_spent NUMERIC(12, 2),
  avg_ticket NUMERIC(12, 2),
  last_order_at TIMESTAMPTZ,
  top_product TEXT
)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  WITH confirmed AS (
    SELECT
      o.id,
      o.user_id,
      o.customer_name,
      lower(o.customer_email) AS customer_email,
      o.customer_whatsapp,
      COALESCE(NULLIF(trim(o.address ->> 'neighborhood'), ''), 'Retirada / Não informado') AS neighborhood,
      o.subtotal,
      o.items,
      o.created_at
    FROM public.orders o
    WHERE o.status NOT IN ('Pendente', 'Cancelado')
  ),
  overall_last AS (
    SELECT c.user_id, MAX(c.created_at) AS overall_last_order_at
    FROM confirmed c
    GROUP BY c.user_id
  ),
  scoped AS (
    SELECT *
    FROM confirmed c
    WHERE (p_start_at IS NULL OR c.created_at >= p_start_at)
      AND (p_end_at IS NULL OR c.created_at <= p_end_at)
  ),
  neighborhood_rank AS (
    SELECT DISTINCT ON (s.user_id)
      s.user_id,
      s.neighborhood AS main_neighborhood
    FROM (
      SELECT user_id, neighborhood, COUNT(*) AS cnt, MAX(created_at) AS latest
      FROM scoped
      GROUP BY user_id, neighborhood
    ) s
    ORDER BY s.user_id, s.cnt DESC, s.latest DESC
  ),
  product_rank AS (
    SELECT DISTINCT ON (p.user_id)
      p.user_id,
      p.product_label AS top_product
    FROM (
      SELECT
        s.user_id,
        trim(
          COALESCE(item ->> 'name', '') ||
          CASE WHEN COALESCE(item ->> 'variation', '') <> '' AND COALESCE(item ->> 'variation', '') <> 'Padrão'
            THEN ' (' || (item ->> 'variation') || ')'
            ELSE ''
          END
        ) AS product_label,
        SUM(COALESCE((item ->> 'quantity')::INTEGER, 1)) AS total_qty
      FROM scoped s
      CROSS JOIN LATERAL jsonb_array_elements(s.items) AS item
      GROUP BY s.user_id, product_label
    ) p
    ORDER BY p.user_id, p.total_qty DESC
  ),
  aggregated AS (
    SELECT
      s.user_id,
      MAX(s.customer_name) AS customer_name,
      MAX(s.customer_email) AS customer_email,
      MAX(s.customer_whatsapp) AS customer_whatsapp,
      COALESCE(nr.main_neighborhood, 'Retirada / Não informado') AS main_neighborhood,
      COUNT(*)::BIGINT AS orders_count,
      ROUND(COALESCE(SUM(s.subtotal), 0)::NUMERIC, 2) AS total_spent,
      ROUND((COALESCE(SUM(s.subtotal), 0) / NULLIF(COUNT(*), 0))::NUMERIC, 2) AS avg_ticket,
      MAX(s.created_at) AS last_order_at,
      COALESCE(pr.top_product, '-') AS top_product,
      ol.overall_last_order_at
    FROM scoped s
    JOIN overall_last ol ON ol.user_id = s.user_id
    LEFT JOIN neighborhood_rank nr ON nr.user_id = s.user_id
    LEFT JOIN product_rank pr ON pr.user_id = s.user_id
    GROUP BY s.user_id, nr.main_neighborhood, pr.top_product, ol.overall_last_order_at
  )
  SELECT
    a.user_id,
    a.customer_name,
    a.customer_email,
    a.customer_whatsapp,
    a.main_neighborhood,
    a.orders_count,
    a.total_spent,
    a.avg_ticket,
    a.last_order_at,
    a.top_product
  FROM aggregated a
  WHERE (
    COALESCE(trim(p_search), '') = ''
    OR lower(a.customer_name) LIKE '%' || lower(trim(p_search)) || '%'
    OR lower(a.customer_email) LIKE '%' || lower(trim(p_search)) || '%'
    OR regexp_replace(a.customer_whatsapp, '\D', '', 'g') LIKE '%' || regexp_replace(trim(p_search), '\D', '', 'g') || '%'
  )
  AND (
    COALESCE(trim(p_neighborhood), '') = ''
    OR lower(a.main_neighborhood) = lower(trim(p_neighborhood))
  )
  AND (
    NOT p_inactive_only
    OR a.overall_last_order_at < NOW() - INTERVAL '30 days'
  )
  ORDER BY
    CASE WHEN p_sort_by = 'orders_count' THEN a.orders_count END DESC NULLS LAST,
    CASE WHEN p_sort_by = 'avg_ticket' THEN a.avg_ticket END DESC NULLS LAST,
    CASE WHEN p_sort_by = 'last_order_at' THEN EXTRACT(EPOCH FROM a.last_order_at) END DESC NULLS LAST,
    a.total_spent DESC,
    a.orders_count DESC;
$$;
