-- Função auxiliar para identificar administrador autenticado via JWT
CREATE OR REPLACE FUNCTION public.is_store_admin()
RETURNS BOOLEAN
LANGUAGE sql
STABLE
AS $$
  SELECT (
    auth.role() = 'service_role'
    OR COALESCE(auth.jwt() ->> 'role', '') = 'admin'
    OR COALESCE(auth.jwt() -> 'app_metadata' ->> 'role', '') = 'admin'
  );
$$;

-- Políticas de PRODUCTS: visitantes podem LER apenas ativos e não excluídos; só admin grava/edita/exclui
DROP POLICY IF EXISTS "Public read active products" ON public.products;
CREATE POLICY "Public read active products"
  ON public.products
  FOR SELECT
  TO anon, authenticated
  USING (active = TRUE AND deleted = FALSE);

DROP POLICY IF EXISTS "Admin full access products" ON public.products;
CREATE POLICY "Admin full access products"
  ON public.products
  FOR ALL
  TO authenticated
  USING (public.is_store_admin())
  WITH CHECK (public.is_store_admin());

